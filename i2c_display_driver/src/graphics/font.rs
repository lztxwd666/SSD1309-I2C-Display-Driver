/// 获取 5×7 字体字符数据。
#[inline]
pub fn glyph(ch: char) -> &'static [u8] {
    if ch == '°' {
        return DEGREE_GLYPH;
    }
    if ch == '↑' {
        return ARROW_UP_GLYPH;
    }
    if ch == '↓' {
        return ARROW_DOWN_GLYPH;
    }
    let idx = ch as usize;
    if !(32..=126).contains(&idx) {
        return &FALLBACK_FONT_DATA[0..5];
    }
    let base = (idx - 32) * 5;
    &FALLBACK_FONT_DATA[base..base + 5]
}

/// 获取 4×6 小号字体字符数据。
#[inline]
pub fn glyph_small(ch: char) -> &'static [u8] {
    if ch == '°' {
        return DEGREE_GLYPH_SMALL;
    }
    let idx = ch as usize;
    if !(32..=126).contains(&idx) {
        return &SMALL_FONT_DATA[0..4];
    }
    let base = (idx - 32) * 4;
    &SMALL_FONT_DATA[base..base + 4]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_a() {
        assert_eq!(glyph('A'), &[0x7E, 0x11, 0x11, 0x11, 0x7E]);
    }

    #[test]
    fn small_digit_0() {
        assert_eq!(glyph_small('0'), &[0x1E, 0x21, 0x21, 0x1E]);
    }

    #[test]
    fn small_font_4_bytes_per_char() {
        for ch in 'A'..='Z' {
            assert_eq!(glyph_small(ch).len(), 4);
        }
    }

    #[test]
    fn degree_works() {
        assert_eq!(glyph('°'), &[0x02, 0x05, 0x05, 0x05, 0x02]);
    }

    #[test]
    fn arrow_up_renders() {
        assert_eq!(glyph('↑'), &[0x04, 0x06, 0x7F, 0x06, 0x04]);
    }

    #[test]
    fn fallback_for_unknown() {
        assert_eq!(glyph('中'), &[0x00, 0x00, 0x00, 0x00, 0x00]);
    }
}